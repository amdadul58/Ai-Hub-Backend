import os
import sqlite3
from pathlib import Path

import psycopg
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
SQLITE_PATH = ROOT / "artifacts" / "ai_hub.sqlite3"

TABLES = [
    "users",
    "conversations",
    "messages",
    "documents",
    "model_versions",
    "training_jobs",
    "inference_logs",
    "traffic_events",
    "audit_logs",
]

SCHEMA = [
    """
    CREATE TABLE users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        email TEXT UNIQUE,
        password_hash TEXT,
        is_active INTEGER NOT NULL DEFAULT 1,
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE conversations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
        title TEXT NOT NULL DEFAULT 'New conversation',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE messages (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id INTEGER NOT NULL
            REFERENCES conversations(id) ON DELETE CASCADE,
        role TEXT NOT NULL,
        content TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE documents (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        filename TEXT NOT NULL,
        file_path TEXT NOT NULL,
        content_type TEXT,
        status TEXT NOT NULL DEFAULT 'uploaded',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE model_versions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        model_name TEXT NOT NULL,
        version TEXT NOT NULL,
        artifact_path TEXT NOT NULL,
        stage TEXT NOT NULL DEFAULT 'staging',
        metrics_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        UNIQUE(model_name, version)
    )
    """,
    """
    CREATE TABLE training_jobs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        job_name TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'pending',
        config_json TEXT NOT NULL DEFAULT '{}',
        result_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
        updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE inference_logs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        model_name TEXT NOT NULL,
        status TEXT NOT NULL,
        latency_ms DOUBLE PRECISION,
        details_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE traffic_events (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        event_type TEXT NOT NULL,
        location TEXT,
        details_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
    """
    CREATE TABLE audit_logs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor TEXT,
        action TEXT NOT NULL,
        resource TEXT,
        details_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    )
    """,
]


def main():
    load_dotenv(ROOT / ".env", override=True)

    database_url = os.getenv("AI_HUB_DATABASE_URL")
    if not database_url:
        raise RuntimeError("AI_HUB_DATABASE_URL is missing from .env")

    if not SQLITE_PATH.is_file():
        raise FileNotFoundError(f"SQLite database not found: {SQLITE_PATH}")

    with sqlite3.connect(
        f"file:{SQLITE_PATH.as_posix()}?mode=ro", uri=True
    ) as source:
        source.row_factory = sqlite3.Row

        source_tables = {
            row["name"]
            for row in source.execute("""
                SELECT name FROM sqlite_master
                WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
            """)
        }

        if not set(TABLES).issubset(source_tables):
            raise RuntimeError("SQLite is missing one or more expected tables.")

        source_counts = {
            table: source.execute(
                f'SELECT COUNT(*) FROM "{table}"'
            ).fetchone()[0]
            for table in TABLES
        }

        with psycopg.connect(database_url) as target:
            existing = target.execute("""
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = 'public'
                  AND table_type = 'BASE TABLE'
            """).fetchall()

            if existing:
                raise RuntimeError(
                    "Target PostgreSQL is not empty. No changes made. "
                    f"Existing tables: {[r[0] for r in existing]}"
                )

            with target.cursor() as cur:
                for statement in SCHEMA:
                    cur.execute(statement)

                for table in TABLES:
                    columns = [
                        row["name"]
                        for row in source.execute(
                            f'PRAGMA table_info("{table}")'
                        )
                    ]

                    rows = source.execute(
                        f'SELECT * FROM "{table}"'
                    ).fetchall()

                    if rows:
                        col_sql = ", ".join(f'"{c}"' for c in columns)
                        placeholders = ", ".join(
                            ["%s"] * len(columns)
                        )
                        insert_sql = (
                            f'INSERT INTO "{table}" ({col_sql}) '
                            f"VALUES ({placeholders})"
                        )

                        cur.executemany(
                            insert_sql,
                            [tuple(row[c] for c in columns) for row in rows],
                        )

                for table in TABLES:
                    cur.execute(
                        f'SELECT COUNT(*) FROM "{table}"'
                    )
                    actual = cur.fetchone()[0]
                    expected = source_counts[table]

                    if actual != expected:
                        raise RuntimeError(
                            f"{table}: expected {expected}, got {actual}"
                        )

                for table in TABLES:
                    cur.execute(
                        f'SELECT COALESCE(MAX(id), 0) FROM "{table}"'
                    )
                    max_id = cur.fetchone()[0]

                    if max_id:
                        cur.execute(
                            """
                            SELECT setval(
                                pg_get_serial_sequence(%s, 'id'),
                                %s,
                                true
                            )
                            """,
                            (f"public.{table}", max_id),
                        )

            # Commit only after all nine table counts match.
            target.commit()

        print("MIGRATION: SUCCESS")
        print("Source SQLite remains unchanged.")
        print("\nVerified row counts:")
        for table, count in source_counts.items():
            print(f"  {table}: {count}")


if __name__ == "__main__":
    main()
