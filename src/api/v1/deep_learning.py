
from importlib.util import find_spec
from pathlib import Path
import json
import secrets

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field

router = APIRouter(prefix="/deep-learning", tags=["Deep Learning"])

ARTIFACT_DIR = Path(__file__).resolve().parents[3] / "artifacts" / "deep_learning"


class TrainRequest(BaseModel):
    samples: list[list[float]] = Field(min_length=2, max_length=2000)
    targets: list[int] = Field(min_length=2, max_length=2000)
    epochs: int = Field(default=5, ge=1, le=100)
    learning_rate: float = Field(default=0.001, gt=0, le=0.1)


class PredictRequest(BaseModel):
    inputs: list[list[float]] = Field(min_length=1, max_length=500)


def _require_torch():
    if find_spec("torch") is None:
        raise HTTPException(
            status_code=503,
            detail="PyTorch is not installed in this environment.",
        )


def _model_paths(model_id: str):
    # Only IDs generated by this API are accepted.
    if (
        len(model_id) != 32
        or any(c not in "0123456789abcdef" for c in model_id)
    ):
        raise HTTPException(status_code=400, detail="Invalid model_id.")

    return (
        ARTIFACT_DIR / f"{model_id}.pt",
        ARTIFACT_DIR / f"{model_id}.json",
    )


def _load_model(model_id: str):
    _require_torch()

    import torch
    from src.deep_learning.architectures.neural_network import build_mlp
    from src.deep_learning.inference.predictor import load_checkpoint

    checkpoint_path, metadata_path = _model_paths(model_id)

    if not checkpoint_path.is_file() or not metadata_path.is_file():
        raise HTTPException(status_code=404, detail="Trained model not found.")

    try:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        model = build_mlp(
            input_features=metadata["input_features"],
            output_features=metadata["output_classes"],
        )
        load_checkpoint(model, checkpoint_path, device="cpu")
        model.eval()
        return model, metadata
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail="Could not load the saved model.",
        ) from exc


