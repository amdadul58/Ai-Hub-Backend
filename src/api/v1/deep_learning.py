@router.post("/train", status_code=201)
def train_deep_learning(request: TrainRequest):
    _require_torch()

    import torch
    from torch.utils.data import DataLoader, TensorDataset
    from src.deep_learning.architectures.neural_network import build_mlp
    from src.deep_learning.training.trainer import train_one_epoch, save_checkpoint

    if len(request.samples) != len(request.targets):
        raise HTTPException(
            status_code=422,
            detail="samples and targets must have the same number of rows.",
        )

    if not request.samples or not request.samples[0]:
        raise HTTPException(status_code=422, detail="Samples cannot be empty.")

    feature_count = len(request.samples[0])

    if any(len(row) != feature_count for row in request.samples):
        raise HTTPException(
            status_code=422,
            detail="Every sample must have the same number of features.",
        )

    if any(not all(__import__("math").isfinite(v) for v in row)
           for row in request.samples):
        raise HTTPException(
            status_code=422,
            detail="Samples must contain finite numeric values.",
        )

    classes = sorted(set(request.targets))
    if len(classes) < 2:
        raise HTTPException(
            status_code=422,
            detail="Classification requires at least two distinct target classes.",
        )

    # Map class labels to consecutive indices for CrossEntropyLoss.
    label_to_index = {label: i for i, label in enumerate(classes)}
    encoded_targets = [label_to_index[y] for y in request.targets]

    torch.manual_seed(42)
    x = torch.tensor(request.samples, dtype=torch.float32)
    y = torch.tensor(encoded_targets, dtype=torch.long)

    loader = DataLoader(
        TensorDataset(x, y),
        batch_size=min(32, len(request.samples)),
        shuffle=True,
    )

    model = build_mlp(feature_count, len(classes))
    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=request.learning_rate,
    )
    loss_function = torch.nn.CrossEntropyLoss()

    history = []
    try:
        for epoch in range(request.epochs):
            result = train_one_epoch(
                model, loader, optimizer, loss_function, device="cpu"
            )
            history.append({
                "epoch": epoch + 1,
                "loss": result["loss"],
                "samples": result["samples"],
            })

        model_id = secrets.token_hex(16)
        ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
        checkpoint_path, metadata_path = _model_paths(model_id)

        save_checkpoint(model, checkpoint_path, optimizer=optimizer,
                        epoch=request.epochs)

        metadata = {
            "model_id": model_id,
            "architecture": "mlp",
            "input_features": feature_count,
            "output_classes": len(classes),
            "class_labels": classes,
            "epochs": request.epochs,
            "samples_trained": len(request.samples),
            "device": "cpu",
            "history": history,
        }
        metadata_path.write_text(
            json.dumps(metadata, indent=2),
            encoding="utf-8",
        )

        return metadata
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail="Model training failed.",
        ) from exc

@router.post("/predict")
def predict_deep_learning(
    request: PredictRequest,
    model_id: str,
):
    return predict_saved_model(model_id, request)


@router.get("/models/{model_id}")
def get_deep_learning_model(model_id: str):
    _, metadata_path = _model_paths(model_id)
    if not metadata_path.is_file():
        raise HTTPException(status_code=404, detail="Trained model not found.")

    try:
        return json.loads(metadata_path.read_text(encoding="utf-8"))
    except Exception as exc:
        raise HTTPException(status_code=500, detail="Invalid model metadata.") from exc


@router.post("/models/{model_id}/predict")
def predict_saved_model(model_id: str, request: PredictRequest):
    import torch
    from src.deep_learning.inference.predictor import predict_batch

    model, metadata = _load_model(model_id)
    expected_features = metadata["input_features"]

    if any(len(row) != expected_features for row in request.inputs):
        raise HTTPException(
            status_code=422,
            detail=f"Each input row must contain {expected_features} features.",
        )

    if any(not all(__import__("math").isfinite(v) for v in row)
           for row in request.inputs):
        raise HTTPException(
            status_code=422,
            detail="Inputs must contain finite numeric values.",
        )

    try:
        inputs = torch.tensor(request.inputs, dtype=torch.float32)
        logits = predict_batch(model, inputs, device="cpu")
        probabilities = torch.softmax(logits, dim=1)
        predicted_indices = probabilities.argmax(dim=1).tolist()

        return {
            "model_id": model_id,
            "predictions": [
                {
                    "class": metadata["class_labels"][index],
                    "probabilities": {
                        str(label): float(probabilities[row, i].item())
                        for i, label in enumerate(metadata["class_labels"])
                    },
                }
                for row, index in enumerate(predicted_indices)
            ],
        }
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail="Prediction failed.",
        ) from exc
