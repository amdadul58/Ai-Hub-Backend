from src.database.session import database_connection

SCHEMA_STATEMENTS = [
    """
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        email TEXT UNIQUE,
        password_hash TEXT,
        is_active INTEGER NOT NULL DEFAULT 1,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS conversations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
        title TEXT NOT NULL DEFAULT 'New conversation',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
        updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS messages (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id INTEGER NOT NULL
            REFERENCES conversations(id) ON DELETE CASCADE,
        role TEXT NOT NULL,
        content TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS documents (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        filename TEXT NOT NULL,
        file_path TEXT NOT NULL,
        content_type TEXT,
        status TEXT NOT NULL DEFAULT 'uploaded',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS model_versions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        model_name TEXT NOT NULL,
        version TEXT NOT NULL,
        artifact_path TEXT NOT NULL,
        stage TEXT NOT NULL DEFAULT 'staging',
        metrics_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
        UNIQUE(model_name, version)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS training_jobs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        job_name TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'pending',
        config_json TEXT NOT NULL DEFAULT '{}',
        result_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
        updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS inference_logs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        model_name TEXT NOT NULL,
        status TEXT NOT NULL,
        latency_ms DOUBLE PRECISION,
        details_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS traffic_events (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        event_type TEXT NOT NULL,
        location TEXT,
        details_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS audit_logs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor TEXT,
        action TEXT NOT NULL,
        resource TEXT,
        details_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id)",
    "CREATE INDEX IF NOT EXISTS idx_inference_model ON inference_logs(model_name)",
    "CREATE INDEX IF NOT EXISTS idx_training_status ON training_jobs(status)",
]


def initialize_database():
    with database_connection() as connection:
        for statement in SCHEMA_STATEMENTS:
            connection.execute(statement)
    return {"status": "initialized", "tables": 9}
